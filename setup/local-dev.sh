#!/usr/bin/env bash
#
# Local development environment setup: /etc/hosts, a wildcard TLS cert, and the
# nginx reverse proxy that fronts every app's Vite dev server.
#
# Why this exists at all:
#   sharpnr-engine issues its auth/CSRF cookies with Secure + SameSite=None on
#   Domain=.sharpnr.test (config/cookieConfig.go). A browser will only store a
#   Secure cookie on a trustworthy origin. http://localhost qualifies, but the
#   cookie's domain does not match it; http://anything.sharpnr.test matches the
#   domain but is NOT trustworthy. So local auth only works over HTTPS on a
#   *.sharpnr.test name -- hence the cert and the proxy.
#
# Everything here is idempotent and safe to re-run. Nothing touches the system
# without --apply.
#
# Usage:
#   ./setup/local-dev.sh check          # report drift, change nothing (default)
#   ./setup/local-dev.sh all --apply    # hosts + certs + nginx
#   ./setup/local-dev.sh nginx --apply
#   ./setup/local-dev.sh uninstall --apply
#
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MANIFEST="$HERE/apps.json"

HOSTS_FILE=/etc/hosts
NGINX_CONF=/etc/nginx/nginx.conf
NGINX_SNIPPET=/etc/nginx/sharpnr-dev.conf
CERT_DIR=/etc/nginx/certs
MARK_BEGIN="# >>> sharpnr local dev (generated by setup/local-dev.sh) >>>"
MARK_END="# <<< sharpnr local dev <<<"

CMD="${1:-check}"
APPLY=0
for a in "$@"; do [ "$a" = "--apply" ] && APPLY=1; done

c_red=$'\e[31m'; c_grn=$'\e[32m'; c_yel=$'\e[33m'; c_dim=$'\e[2m'; c_off=$'\e[0m'
info(){ printf '%s\n' "$*"; }
ok(){   printf '%s✓%s %s\n' "$c_grn" "$c_off" "$*"; }
warn(){ printf '%s!%s %s\n' "$c_yel" "$c_off" "$*"; }
err(){  printf '%s✗%s %s\n' "$c_red" "$c_off" "$*" >&2; }
dim(){  printf '%s%s%s\n' "$c_dim" "$*" "$c_off"; }

need(){ command -v "$1" >/dev/null 2>&1 || { err "missing required tool: $1"; exit 1; }; }
need jq; need nginx; need mkcert

DOMAIN=$(jq -r .domain "$MANIFEST")
WILDCARD_CERT="$CERT_DIR/_wildcard.$DOMAIN.pem"
WILDCARD_KEY="$CERT_DIR/_wildcard.$DOMAIN-key.pem"

# rows: host<TAB>port<TAB>name
rows(){ jq -r '.apps[] | [.host, (.port|tostring), .name] | @tsv' "$MANIFEST"; }

sudo_do(){
  if [ "$APPLY" -eq 0 ]; then dim "   would run: $*"; return 0; fi
  sudo "$@"
}

# ---------------------------------------------------------------- hosts

gen_hosts(){
  echo "$MARK_BEGIN"
  while IFS=$'\t' read -r host port name; do
    printf '127.0.0.1\t%s\n' "$host"
  done < <(rows)
  echo "$MARK_END"
}

do_hosts(){
  info "── /etc/hosts"
  local missing=0
  while IFS=$'\t' read -r host port name; do
    if grep -qE "^[^#]*[[:space:]]$host([[:space:]]|$)" "$HOSTS_FILE"; then
      :
    else
      warn "missing: $host"; missing=$((missing+1))
    fi
  done < <(rows)

  if [ "$missing" -eq 0 ]; then ok "all $(rows | wc -l) hosts present"; return 0; fi

  local tmp; tmp=$(mktemp)
  # drop any previous generated block, keep everything else verbatim
  awk -v b="$MARK_BEGIN" -v e="$MARK_END" '
    $0==b{skip=1} !skip{print} $0==e{skip=0}
  ' "$HOSTS_FILE" > "$tmp"
  gen_hosts >> "$tmp"

  if [ "$APPLY" -eq 0 ]; then
    dim "   would add $missing entr(y|ies) to $HOSTS_FILE"
    rm -f "$tmp"; return 0
  fi
  sudo cp "$HOSTS_FILE" "$HOSTS_FILE.bak.$(date +%Y%m%d_%H%M%S)"
  sudo cp "$tmp" "$HOSTS_FILE"; rm -f "$tmp"
  ok "hosts updated"
}

# ---------------------------------------------------------------- certs

do_certs(){
  info "── TLS certificate"
  if [ ! -f "$(mkcert -CAROOT)/rootCA.pem" ]; then
    warn "mkcert CA not installed"
    sudo_do mkcert -install
  else
    ok "mkcert CA present"
  fi

  # The .pem is world-readable (only the key is 0600), so no sudo needed here --
  # using sudo made this silently report "missing" whenever there was no tty.
  if [ -r "$WILDCARD_CERT" ]; then
    local exp
    exp=$(openssl x509 -enddate -noout -in "$WILDCARD_CERT" 2>/dev/null | cut -d= -f2 || echo "?")
    if openssl x509 -checkend 604800 -noout -in "$WILDCARD_CERT" >/dev/null 2>&1; then
      ok "wildcard cert valid (expires $exp)"
      return 0
    fi
    warn "cert expires within 7 days ($exp) -- regenerating"
  else
    warn "no wildcard cert at $WILDCARD_CERT"
  fi

  if [ "$APPLY" -eq 0 ]; then
    dim "   would generate *.$DOMAIN + $DOMAIN cert into $CERT_DIR"
    return 0
  fi
  sudo mkdir -p "$CERT_DIR"
  ( cd "$(mktemp -d)" && mkcert "*.$DOMAIN" "$DOMAIN" \
      && sudo cp "_wildcard.$DOMAIN.pem" "$WILDCARD_CERT" \
      && sudo cp "_wildcard.$DOMAIN-key.pem" "$WILDCARD_KEY" )
  ok "wildcard cert generated"
}

# ---------------------------------------------------------------- nginx

gen_nginx(){
  cat <<EOF
$MARK_BEGIN
#
# Generated from setup/apps.json -- do not hand-edit. Re-run:
#   ./setup/local-dev.sh nginx --apply
#
# Every app is proxied to its Vite dev server over HTTPS so that the
# Secure + SameSite=None cookies from sharpnr-engine are actually stored.

server {
    listen 80;
    server_name .$DOMAIN;
    return 301 https://\$host\$request_uri;
}
EOF

  while IFS=$'\t' read -r host port name; do
    cat <<EOF

# $name
server {
    listen 443 ssl;
    http2 on;
    server_name $host;

    ssl_certificate     $WILDCARD_CERT;
    ssl_certificate_key $WILDCARD_KEY;

    # Vite dev servers stream large unbundled module graphs; don't buffer.
    proxy_buffering off;
    client_max_body_size 50m;

    location / {
        proxy_pass http://127.0.0.1:$port;
        proxy_http_version 1.1;

        # Vite HMR runs over a websocket. Without these the app loads but
        # never hot-reloads, which is a confusing failure to debug.
        # \$connection_upgrade is the map defined in nginx.conf: it sends
        # "upgrade" only for real websocket requests and "close" otherwise.
        # Hardcoding "upgrade" here sent an invalid Connection header on every
        # plain HTTP request and defeated upstream keepalive.
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$connection_upgrade;

        # Vite checks this against server.allowedHosts.
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto https;

        proxy_read_timeout 86400;
    }
}
EOF
  done < <(rows)

  echo "$MARK_END"
}

do_nginx(){
  info "── nginx"

  local tmp; tmp=$(mktemp); gen_nginx > "$tmp"

  # Does the live config already define these names inline? Two server blocks
  # with the same server_name means nginx silently ignores one of them.
  local inline=0
  if grep -qE "server_name[[:space:]]+[a-z.]*$DOMAIN" "$NGINX_CONF" 2>/dev/null; then
    if ! grep -q "$MARK_BEGIN" "$NGINX_CONF" 2>/dev/null; then
      inline=$(grep -cE "server_name[[:space:]]+[a-z.]*$DOMAIN" "$NGINX_CONF" || true)
    fi
  fi

  if [ "$inline" -gt 0 ]; then
    err "$NGINX_CONF has $inline hand-written $DOMAIN server block(s)."
    info "   Installing this snippet alongside them would create duplicate"
    info "   server_name entries and nginx would ignore one set."
    info ""
    info "   Remove those blocks from $NGINX_CONF first, leaving an include:"
    info "       include $NGINX_SNIPPET;"
    info ""
    dim  "   A copy of the generated snippet is at: $HERE/generated/sharpnr-dev.conf"
    mkdir -p "$HERE/generated"; cp "$tmp" "$HERE/generated/sharpnr-dev.conf"
    rm -f "$tmp"
    return 1
  fi

  if [ "$APPLY" -eq 0 ]; then
    mkdir -p "$HERE/generated"; cp "$tmp" "$HERE/generated/sharpnr-dev.conf"
    dim "   would install $(rows | wc -l) server blocks to $NGINX_SNIPPET"
    dim "   preview written to setup/generated/sharpnr-dev.conf"
    rm -f "$tmp"; return 0
  fi

  sudo cp "$NGINX_CONF" "$NGINX_CONF.bak.$(date +%Y%m%d_%H%M%S)"
  sudo cp "$tmp" "$NGINX_SNIPPET"; rm -f "$tmp"

  if ! grep -q "include $NGINX_SNIPPET;" "$NGINX_CONF"; then
    # insert the include as the last line inside the http { } block
    sudo awk -v inc="    include $NGINX_SNIPPET;" '
      /^\}/ && !done && seen_http { print inc; done=1 }
      /http[[:space:]]*\{/ { seen_http=1 }
      { print }
    ' "$NGINX_CONF" > /tmp/.nginx.new && sudo cp /tmp/.nginx.new "$NGINX_CONF"
    rm -f /tmp/.nginx.new
  fi

  # Never reload a config that does not parse.
  if sudo nginx -t 2>/dev/null; then
    sudo systemctl reload nginx
    ok "nginx reloaded with $(rows | wc -l) server blocks"
  else
    err "nginx -t failed; restoring backup and NOT reloading"
    sudo cp "$(ls -t $NGINX_CONF.bak.* | head -1)" "$NGINX_CONF"
    sudo nginx -t
    return 1
  fi
}

# ---------------------------------------------------------------- checks

do_check(){
  info "── port assignments"
  local dupes
  dupes=$(rows | awk -F'\t' '{print $2}' | sort | uniq -d)
  if [ -n "$dupes" ]; then
    err "duplicate ports in apps.json: $dupes"
  else
    ok "all $(rows | wc -l) ports unique"
  fi

  info "── running dev servers"
  while IFS=$'\t' read -r host port name; do
    if ss -ltn 2>/dev/null | grep -q ":$port "; then
      ok "$(printf '%-28s' "$host") :$port up"
    else
      dim "  $(printf '%-28s' "$host") :$port down"
    fi
  done < <(rows)
}

do_uninstall(){
  info "── uninstall"
  if [ "$APPLY" -eq 0 ]; then
    dim "   would strip the generated block from $HOSTS_FILE"
    dim "   would remove $NGINX_SNIPPET and its include"
    return 0
  fi
  local tmp; tmp=$(mktemp)
  awk -v b="$MARK_BEGIN" -v e="$MARK_END" '$0==b{skip=1} !skip{print} $0==e{skip=0}' \
    "$HOSTS_FILE" > "$tmp"
  sudo cp "$tmp" "$HOSTS_FILE"; rm -f "$tmp"
  sudo rm -f "$NGINX_SNIPPET"
  sudo sed -i "\|include $NGINX_SNIPPET;|d" "$NGINX_CONF"
  sudo nginx -t && sudo systemctl reload nginx
  ok "removed"
}

case "$CMD" in
  check)     do_check; do_hosts; do_certs; do_nginx || true ;;
  hosts)     do_hosts ;;
  certs)     do_certs ;;
  nginx)     do_nginx ;;
  all)       do_hosts; do_certs; do_nginx ;;
  uninstall) do_uninstall ;;
  *) err "unknown command: $CMD"; sed -n '18,24p' "$0"; exit 2 ;;
esac

if [ "$APPLY" -eq 0 ] && [ "$CMD" != "check" ]; then
  info ""
  dim "dry run -- nothing changed. re-run with --apply"
fi
