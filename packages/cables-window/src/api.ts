import { api } from "@sharpnr/http";
import type {
  CablesBootstrap,
  CablesConversation,
  CablesMessage,
  CablesMessagePage,
} from "./types";

/**
 * The subset of the cables API a docked DM window needs.
 *
 * It goes through the suite's shared axios client, so the session cookie, the
 * CSRF header and the redirect-to-auth behaviour are already whatever the host
 * app has configured. There is no separate auth story for this widget.
 */

type Envelope<T> = { success: boolean; message?: string; data?: T };

const Endpoints = {
  bootstrap: "/cables/bootstrap",
  conversations: "/cables/conversations",
  openDirect: "/cables/conversations/direct",
  messages: (id: string) => `/cables/conversations/${id}/messages`,
  read: (id: string) => `/cables/conversations/${id}/read`,
};

export async function fetchBootstrap(): Promise<CablesBootstrap | null> {
  const res = await api.get<Envelope<CablesBootstrap>>(Endpoints.bootstrap);
  return res.data.data ?? null;
}

export async function fetchConversations(): Promise<CablesConversation[]> {
  const res = await api.get<Envelope<CablesConversation[]>>(
    Endpoints.conversations,
  );
  return res.data.data ?? [];
}

export async function fetchMessages(
  conversationId: string,
): Promise<CablesMessagePage> {
  const res = await api.get<Envelope<CablesMessagePage>>(
    Endpoints.messages(conversationId),
  );
  return res.data.data ?? { messages: [], hasMore: false };
}

/**
 * `clientMessageId` is generated by the caller before the request, so a retry
 * over a flaky connection resolves to the row already written rather than
 * posting the message twice.
 */
export async function postMessage(
  conversationId: string,
  body: string,
  clientMessageId: string,
): Promise<CablesMessage | null> {
  const res = await api.post<Envelope<CablesMessage>>(
    Endpoints.messages(conversationId),
    { body, clientMessageId },
  );
  return res.data.data ?? null;
}

export async function markRead(conversationId: string, seq: number) {
  await api.post(Endpoints.read(conversationId), { seq });
}

export async function openDirect(
  memberId: string,
): Promise<CablesConversation | null> {
  const res = await api.post<Envelope<CablesConversation>>(
    Endpoints.openDirect,
    { memberId },
  );
  return res.data.data ?? null;
}
